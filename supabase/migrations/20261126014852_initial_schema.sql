-- Baseline for a NEW database. Existing databases must be inspected and reconciled first.
-- No DROP/TRUNCATE and no demo users or passwords. Run as the database owner.
BEGIN;

CREATE TABLE public.usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  email text NOT NULL,
  password_hash text NOT NULL,
  rol text NOT NULL CHECK (rol IN ('admin', 'inspector')),
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX usuarios_email_unique ON public.usuarios (lower(btrim(email)));

CREATE TABLE public.empresas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  rut text NOT NULL UNIQUE,
  rubro text,
  productos_transportados text,
  telefono_contacto text,
  email_contacto text,
  direccion text,
  prioridad_frio boolean NOT NULL DEFAULT false,
  prioridad_carroceria boolean NOT NULL DEFAULT false,
  prioridad_estructura boolean NOT NULL DEFAULT false,
  prioridad_camion boolean NOT NULL DEFAULT false,
  prioridad_acople boolean NOT NULL DEFAULT false,
  pin_hash text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresas(id),
  nombre text NOT NULL,
  rut text UNIQUE,
  direccion text,
  nombre_contacto text,
  telefono_contacto text,
  email_contacto text,
  tipo_transportista text NOT NULL DEFAULT 'no_licitado'
    CHECK (tipo_transportista IN ('licitado', 'no_licitado')),
  tipo_entidad text NOT NULL DEFAULT 'empresa' CHECK (tipo_entidad IN ('empresa', 'persona')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX proveedores_empresa_idx ON public.proveedores(empresa_id);

CREATE TABLE public.camiones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id integer NOT NULL REFERENCES public.proveedores(id),
  patente text NOT NULL CHECK (patente = upper(regexp_replace(btrim(patente), '\s+', '', 'g')) AND patente <> ''),
  marca text,
  modelo text,
  anio integer CHECK (anio BETWEEN 1900 AND 2200),
  tipo text NOT NULL DEFAULT 'camion' CHECK (tipo IN ('camion', 'acople')),
  carroceria text CHECK (carroceria IN ('camion_con_carro', 'carro_reefer', 'camara_de_frio', 'camion_paquetero', 'camion_carro_paquetero')),
  tipo_remolque text,
  estado text NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'MANTENCION', 'INACTIVO')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (proveedor_id, patente)
);

CREATE TABLE public.camion_fotos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camion_id integer NOT NULL UNIQUE REFERENCES public.camiones(id) ON DELETE CASCADE,
  url text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.inspecciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camion_id integer NOT NULL REFERENCES public.camiones(id),
  inspector_id integer REFERENCES public.usuarios(id),
  fecha_programada timestamptz NOT NULL,
  fecha_inspeccion timestamptz,
  fecha_realizada timestamptz,
  estado text NOT NULL DEFAULT 'PROGRAMADA' CHECK (estado IN ('PROGRAMADA', 'REALIZADA', 'CANCELADA')),
  resultado_general text NOT NULL DEFAULT 'PENDIENTE'
    CHECK (resultado_general IN ('PENDIENTE', 'APROBADO', 'OBSERVADO', 'RECHAZADO')),
  nota_final double precision CHECK (nota_final BETWEEN 0 AND 100),
  observaciones_generales text,
  resultado_detallado text,
  revision_admin text NOT NULL DEFAULT 'PENDIENTE'
    CHECK (revision_admin IN ('PENDIENTE', 'APROBADA_OK', 'APROBADA_CON_FALLAS', 'RECHAZADA', 'REAGENDADA', 'ANULADA')),
  comentario_admin text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX inspecciones_programada_unique ON public.inspecciones(camion_id) WHERE estado = 'PROGRAMADA';
CREATE INDEX inspecciones_inspector_fecha_idx ON public.inspecciones(inspector_id, fecha_programada);
CREATE INDEX inspecciones_camion_fecha_idx ON public.inspecciones(camion_id, fecha_inspeccion DESC);

CREATE TABLE public.detalle_inspeccion (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspeccion_id integer NOT NULL REFERENCES public.inspecciones(id) ON DELETE CASCADE,
  camion_id integer REFERENCES public.camiones(id),
  item_id text NOT NULL,
  resultado text NOT NULL CHECK (resultado IN ('cumple', 'no_cumple', 'no_aplica')),
  estado_item text NOT NULL CHECK (estado_item IN ('cumple', 'no_cumple', 'no_aplica')),
  descripcion_falla text,
  observacion text,
  motivo_no_aplica text,
  categoria text NOT NULL DEFAULT 'General',
  nivel integer NOT NULL DEFAULT 1 CHECK (nivel BETWEEN 1 AND 4),
  seccion text NOT NULL DEFAULT 'General',
  resultado_admin text CHECK (resultado_admin IN ('aprobado', 'rechazado', 'no_aplica')),
  comentario_admin text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (inspeccion_id, item_id)
);

CREATE INDEX detalle_inspeccion_camion_idx ON public.detalle_inspeccion(camion_id);

CREATE TABLE public.fotos_inspeccion (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  detalle_inspeccion_id integer NOT NULL REFERENCES public.detalle_inspeccion(id) ON DELETE CASCADE,
  nombre_archivo text NOT NULL,
  url_archivo text,
  datos_binarios bytea,
  tipo_mime text NOT NULL DEFAULT 'image/jpeg',
  fecha_captura timestamptz NOT NULL DEFAULT now(),
  latitud double precision CHECK (latitud BETWEEN -90 AND 90),
  longitud double precision CHECK (longitud BETWEEN -180 AND 180)
);
CREATE UNIQUE INDEX fotos_inspeccion_url_unique ON public.fotos_inspeccion(detalle_inspeccion_id, url_archivo) WHERE url_archivo IS NOT NULL;
CREATE INDEX fotos_inspeccion_detalle_idx ON public.fotos_inspeccion(detalle_inspeccion_id);

CREATE TABLE public.notificaciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id),
  inspeccion_id integer REFERENCES public.inspecciones(id),
  tipo text NOT NULL,
  titulo text NOT NULL,
  mensaje text,
  leida boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notificaciones_inspeccion_idx ON public.notificaciones(inspeccion_id);
CREATE INDEX notificaciones_usuario_idx ON public.notificaciones(usuario_id, leida, created_at DESC);

-- The app uses its own signed server-side sessions, not Supabase Auth JWTs.
-- All database access goes through Next.js using a server-only database login.
-- Grant that login membership in petran_backend; it needs no ownership or BYPASSRLS.
-- No browser access to password/PIN hashes or business data through the Data API.
DO $$
DECLARE table_name text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'petran_backend') THEN
    CREATE ROLE petran_backend NOLOGIN;
  END IF;
  GRANT USAGE ON SCHEMA public TO petran_backend;
  FOREACH table_name IN ARRAY ARRAY['usuarios','empresas','proveedores','camiones','camion_fotos','inspecciones','detalle_inspeccion','fotos_inspeccion','notificaciones'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC', table_name);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE ON TABLE public.%I TO petran_backend', table_name);
    EXECUTE format('GRANT USAGE ON SEQUENCE public.%I TO petran_backend', table_name || '_id_seq');
    EXECUTE format('CREATE POLICY backend_access ON public.%I TO petran_backend USING (true) WITH CHECK (true)', table_name);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon', table_name);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM authenticated', table_name);
    END IF;
  END LOOP;
END $$;

COMMIT;
